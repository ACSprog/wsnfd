"""Write every table and figure of Chapter 6 from one or more results folders.
    python -m wsnfd.report results/intel_fsA [results/intel_fsB ...] --out report_out [--margin 0.02]
Produces: tables/*.csv (including block_curves.csv), results.xlsx, figures/*.png, bundle.zip (with each run's environment.json under run_files/), README.txt."""
import argparse, os, zipfile
import pandas as pd
from . import analyse as A, plots as P, interop as IO

def file_tag(runs, limit=80):
    """The names of the runs in a set of results, safe for a file name (e.g. FS-B-Main-Run+FS-A-Main-Run); long lists are shortened."""
    import re
    labs = [re.sub(r"[^A-Za-z0-9._-]+", "-", str(l)).strip("-") for l in (sorted(runs.run_label.dropna().unique()) if "run_label" in runs.columns else [])] or ["results"]
    tag = "+".join(labs)
    return tag if len(tag) <= limit else "+".join(labs[:2]) + f"+{len(labs) - 2}-more"

def build_tables(runs, blocks, margin=0.02):
    T = A.tests(runs, margin=margin)
    return {"summary": A.summary(runs), "recovery": A.recovery_table(runs), "cost": A.cost_table(runs), "gain_per_cost": A.gain_per_cost(runs),
            "tests_post_change_f1": T, "worthwhile": A.worthwhile(T, runs, margin) if len(T) else pd.DataFrame(),
            "change_effects": A.change_effects(runs, "post_change_f1", margin, "M1" if "M1" in set(runs.model) else sorted(runs.model.unique())[0]),
            "recall_by_fault_type": A.recall_by_type(runs),
            "raw_runs": runs}

def build_figures(runs, blocks):
    figs = {}
    labels = A.ctx(blocks, ("run_label",)) and sorted(blocks.run_label.unique()) or [None]
    for lab in labels:
        for sc in sorted(blocks.scenario.unique()):
            r = runs[(runs.scenario == sc) & ((runs.run_label == lab) if lab else True)]
            onset = int(r.onset_block.iloc[0]) if "onset_block" in r.columns and len(r) else None
            figs[f"blocks_{(lab + '_') if lab else ''}{sc}"] = P.fig_blocks(blocks, sc, onset, lab)
    figs["post_change_f1_box"] = P.fig_box(runs, "post_change_f1", "scenario", "model")
    figs["post_change_f1_bar"] = P.fig_bar(runs, "post_change_f1", "scenario", "model")
    figs["recall_by_fault_type"] = P.fig_recall(runs); figs["cost"] = P.fig_cost(runs)
    return figs

def write_all(runs, blocks, out, margin=0.02, extra_files=None):
    os.makedirs(f"{out}/tables", exist_ok=True); os.makedirs(f"{out}/figures", exist_ok=True)
    tabs = build_tables(runs, blocks, margin); written = []
    for k, df in tabs.items():
        p = f"{out}/tables/{k}.csv"; df.to_csv(p, index=False); written.append(p)
    bp = f"{out}/tables/block_curves.csv"; blocks.to_csv(bp, index=False); written.append(bp)      # the F1 of every block, the numbers behind the block charts
    xl = f"{out}/results.xlsx"
    with pd.ExcelWriter(xl) as w:
        for k, df in tabs.items():
            if k == "raw_runs" or len(df): df.to_excel(w, sheet_name=k[:31], index=False)
    written.append(xl)
    mp = f"{out}/results.mat"; IO.tables_to_mat(tabs, mp); written.append(mp)
    nbp = f"{out}/analysis.ipynb"; open(nbp, "w").write(IO.make_notebook()); written.append(nbp)
    for name, txt in IO.SCRIPTS.items():
        sp = f"{out}/{name}"; open(sp, "w").write(txt); written.append(sp)
    for k, fig in build_figures(runs, blocks).items():
        p = f"{out}/figures/{k}.png"; open(p, "wb").write(P.to_png(fig)); written.append(p)
    open(f"{out}/README.txt", "w").write(
        f"Runs in this bundle: {', '.join(sorted(runs.run_label.dropna().unique())) if 'run_label' in runs.columns else 'not named'}.\n"
        "Tables (CSV, results.xlsx, results.mat) and figures (PNG) generated by wsnfd.report.\n"
        "Open in MATLAB, R, Python or Jupyter with load_in_matlab.m, load_in_R.R, load_in_python.py or analysis.ipynb.\n"
        f"Practical margin used for tests: {margin}. Seeds share one real stream, so inference is limited to this data source.\n")
    written.append(f"{out}/README.txt")
    z = f"{out}/bundle.zip"
    with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
        for p in written: zf.write(p, os.path.relpath(p, out))
        for p in (extra_files or []): zf.write(p, os.path.join("run_files", os.path.basename(os.path.dirname(p)) + "_" + os.path.basename(p)))
    written.append(z); return written

def main(argv=None):
    ap = argparse.ArgumentParser(); ap.add_argument("folders", nargs="+"); ap.add_argument("--out", default="report_out"); ap.add_argument("--margin", type=float, default=0.02)
    a = ap.parse_args(argv); runs, blocks = A.load_folders(a.folders)
    env = [os.path.join(f, "environment.json") for f in a.folders if os.path.exists(os.path.join(f, "environment.json"))]      # the settings and tuning scores of each run
    for p in write_all(runs, blocks, a.out, a.margin, extra_files=env): print(p)

if __name__ == "__main__":
    main()
